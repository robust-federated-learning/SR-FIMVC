clear; clc;
root=fileparts(mfilename('fullpath'));
addpath(root,'-begin');
[Xlist,gt,k,~]=load_dataset_by_name('Handwritten');
cfg=struct('data_dir',fullfile(root,'data'),'T',3,'anchor_m',30, ...
    'anchor_s',3,'kmeans_reps',20,'smart_axis',false,'metric','cosine', ...
    'R_anchor',4,'R_comm',3,'lambda1',1,'lambda2',1, ...
    'lambda_graph',0.5,'lambda_align',0.1,'structure_z_enabled',false, ...
    'z_solver','projected','z_projected_max_iter',5, ...
    'z_projected_max_backtracks',12,'z_projected_tol',1e-6);
cfg.X_raw=Xlist; cfg.gt_raw=gt; cfg.k=k;
rates=[0.3,0.5];
paired=repmat(struct('PER',[],'base',[],'projected',[], ...
    'base_seconds',[],'projected_seconds',[],'z_step_norms',[], ...
    'z_solve_seconds',[],'z_orth_errors',[]),1,numel(rates));
summary=zeros(numel(rates),15);
for j=1:numel(rates)
    cfg.PER=rates(j); cfg.structure_z_enabled=false;
    timer=tic; base=main_fed_SR_FIMVC('Handwritten',1,cfg); base_seconds=toc(timer);
    cfg.structure_z_enabled=true;
    timer=tic; revised=main_fed_SR_FIMVC('Handwritten',1,cfg); revised_seconds=toc(timer);
    assert(isequal(base.protocol.missing_rows,revised.protocol.missing_rows));
    assert(isequal(base.protocol.initial_assign,revised.protocol.initial_assign));
    updates=revised.logs.z_updates(~cellfun(@isempty,revised.logs.z_updates));
    step_norms=cellfun(@(q)q.step_norm,updates);
    solve_seconds=cellfun(@(q)q.solve_seconds,updates);
    orth_errors=cellfun(@(q)q.orth_error,updates);
    summary(j,:)=[rates(j),base.final.acc,revised.final.acc, ...
        base.final.nmi,revised.final.nmi,base.final.ari,revised.final.ari, ...
        base.evaluation.completion_rmse_mean,revised.evaluation.completion_rmse_mean, ...
        base.evaluation.completion_nrmse_mean,revised.evaluation.completion_nrmse_mean, ...
        base_seconds,revised_seconds,max(step_norms),max(orth_errors)];
    paired(j)=struct('PER',rates(j),'base',base,'projected',revised, ...
        'base_seconds',base_seconds,'projected_seconds',revised_seconds, ...
        'z_step_norms',step_norms,'z_solve_seconds',solve_seconds, ...
        'z_orth_errors',orth_errors);
end
summary_table=array2table(summary,'VariableNames', ...
    {'PER','BaseACC','ProjectedACC','BaseNMI','ProjectedNMI', ...
     'BaseARI','ProjectedARI','BaseRMSE','ProjectedRMSE', ...
     'BaseNRMSE','ProjectedNRMSE','BaseSeconds','ProjectedSeconds', ...
     'MaxZStep','MaxOrthError'});
disp(summary_table);
save(fullfile(root,'results_projected_Z_Handwritten.mat'),'paired','summary_table','cfg','-v7.3');
writetable(summary_table,fullfile(root,'results_projected_Z_Handwritten.csv'));
