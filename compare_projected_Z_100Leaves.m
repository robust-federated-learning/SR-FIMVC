clear; clc;
root=fileparts(mfilename('fullpath'));
addpath(root,'-begin');
[Xlist,gt,k,~]=load_dataset_by_name('100Leaves');
cfg=struct('data_dir',fullfile(root,'data'),'T',3,'PER',0.1, ...
    'anchor_m',k,'anchor_s',3,'pn',5,'R_anchor',4,'R_comm',1, ...
    'smart_axis',false,'metric','euclidean','kmeans_reps',50, ...
    'use_raw_init',true,'lambda1',1,'lambda2',1, ...
    'lambda_graph',0.5,'lambda_align',0.1,'z_solver','projected', ...
    'z_projected_max_iter',5,'z_projected_max_backtracks',12, ...
    'z_projected_tol',1e-6);
cfg.X_raw=Xlist; cfg.gt_raw=gt; cfg.k=k;
cfg.structure_z_enabled=false;
timer=tic; base=main_fed_SR_FIMVC('100Leaves',1,cfg); base_seconds=toc(timer);
cfg.structure_z_enabled=true;
timer=tic; projected=main_fed_SR_FIMVC('100Leaves',1,cfg); projected_seconds=toc(timer);
assert(isequal(base.protocol.missing_rows,projected.protocol.missing_rows));
updates=projected.logs.z_updates(~cellfun(@isempty,projected.logs.z_updates));
summary_table=table(base.final.acc,projected.final.acc, ...
    base.final.nmi,projected.final.nmi,base.final.ari,projected.final.ari, ...
    base.evaluation.completion_rmse_mean,projected.evaluation.completion_rmse_mean, ...
    base_seconds,projected_seconds,max(cellfun(@(q)q.step_norm,updates)), ...
    max(cellfun(@(q)q.orth_error,updates)), ...
    'VariableNames',{'BaseACC','ProjectedACC','BaseNMI','ProjectedNMI', ...
    'BaseARI','ProjectedARI','BaseRMSE','ProjectedRMSE','BaseSeconds', ...
    'ProjectedSeconds','MaxZStep','MaxOrthError'});
disp(summary_table);
save(fullfile(root,'results_projected_Z_100Leaves.mat'), ...
    'base','projected','summary_table','cfg','-v7.3');
writetable(summary_table,fullfile(root,'results_projected_Z_100Leaves.csv'));
