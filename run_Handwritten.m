function run_Handwritten
% Run the clean SR-FIMVC experiment on the Handwritten dataset.
    clc;
    script_root = fileparts(mfilename('fullpath'));
    addpath(script_root, '-begin');

    % Set true for the formal 10-run experiment. Keep false for a quick
    % end-to-end validation before launching the full experiment.
    FORMAL_MODE = false;

    PER_LIST = [0.0, 0.1, 0.3, 0.5];
    PN_NEIGHBORS = 15;
    KMEANS_REPS = 20;
    LAMBDA_GRAPH = 0.5;
    LAMBDA_ALIGN = 0.1;
    COMPLETION_GRAPH_WEIGHT = 1.0;

    if FORMAL_MODE
        NUM_RUNS = 10;
        T_MAX = 200;
        ANCHOR_M = 300;
        R_ANCHOR = 10;
        Z_PROJECTED_MAX_ITER = 5;
        profile = 'formal';
    else
        NUM_RUNS = 1;
        T_MAX = 3;
        ANCHOR_M = 30;
        R_ANCHOR = 4;
        Z_PROJECTED_MAX_ITER = 3;
        profile = 'quick';
    end

    data_file = fullfile(script_root, 'data', 'Handwritten.mat');
    results_dir = fullfile(script_root, 'results');
    if exist(results_dir, 'dir') ~= 7
        mkdir(results_dir);
    end
    [Xlist, gt, k] = load_handwritten_data(data_file);

    config_base = struct( ...
        'T', T_MAX, ...
        'use_anchor', true, ...
        'anchor_m', ANCHOR_M, ...
        'anchor_s', 3, ...
        'pn', PN_NEIGHBORS, ...
        'R_anchor', R_ANCHOR, ...
        'R_comm', 3, ...
        'warm_start_iter', 50, ...
        'smart_axis', false, ...
        'metric', 'cosine', ...
        'kmeans_reps', KMEANS_REPS, ...
        'rwc_enabled', true, ...
        'structure_z_enabled', true, ...
        'z_solver', 'projected', ...
        'lambda1', 1.0, ...
        'lambda2', 1.0, ...
        'z_projected_max_iter', Z_PROJECTED_MAX_ITER, ...
        'z_projected_max_backtracks', 12, ...
        'z_projected_tol', 1e-6, ...
        'h_gradient_mode', 'objective', ...
        'h_monotone_safeguard', true, ...
        'completion_init_mode', 'mean', ...
        'completion_graph_weight', COMPLETION_GRAPH_WEIGHT, ...
        'completion_graph_max_iter', 10, ...
        'completion_graph_max_backtracks', 12, ...
        'completion_graph_tol', 1e-6, ...
        'completion_graph_normalize', true, ...
        'local_approx_mode', 'orthogonal_bcd', ...
        'local_approx_max_iter', 50, ...
        'server_consensus_mode', 'orthogonal_bcd', ...
        'server_consensus_max_iter', 50, ...
        'lambda_graph', LAMBDA_GRAPH, ...
        'lambda_align', LAMBDA_ALIGN, ...
        'X_raw', {Xlist}, ...
        'gt_raw', gt, ...
        'k', k);

    fprintf('======================================================\n');
    fprintf('  SR-FIMVC HANDWRITTEN EXPERIMENT\n');
    fprintf('  PROFILE=%s, RUNS=%d, T=%d, ANCHORS=%d\n', ...
            upper(profile), NUM_RUNS, T_MAX, ANCHOR_M);
    fprintf('  PER=[%s]\n', num2str(PER_LIST));
    fprintf('======================================================\n');

    results_table = table();
    all_runs_details = struct('PER', {}, 'RUN_ID', {}, 'R', {});
    detail_counter = 1;
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    checkpoint_file = fullfile(results_dir, ...
        sprintf('checkpoint_Handwritten_%s_%s.mat', profile, timestamp));

    for p = 1:numel(PER_LIST)
        current_per = PER_LIST(p);
        acc_runs = zeros(NUM_RUNS, 1);
        nmi_runs = zeros(NUM_RUNS, 1);
        ari_runs = zeros(NUM_RUNS, 1);
        purity_runs = zeros(NUM_RUNS, 1);
        rmse_runs = zeros(NUM_RUNS, 1);
        nrmse_runs = zeros(NUM_RUNS, 1);

        fprintf('\n--- PER=%.2f: %d run(s) ---\n', current_per, NUM_RUNS);
        for run_id = 1:NUM_RUNS
            config = config_base;
            config.PER = current_per;
            timer = tic;
            R = main_fed_SR_FIMVC('Handwritten', run_id, config);

            acc_runs(run_id) = R.final.acc;
            nmi_runs(run_id) = R.final.nmi;
            ari_runs(run_id) = R.final.ari;
            purity_runs(run_id) = R.final.purity;
            rmse_runs(run_id) = R.evaluation.completion_rmse_mean;
            nrmse_runs(run_id) = R.evaluation.completion_nrmse_mean;

            all_runs_details(detail_counter).PER = current_per;
            all_runs_details(detail_counter).RUN_ID = run_id;
            all_runs_details(detail_counter).R = R;
            detail_counter = detail_counter + 1;

            fprintf(['[PER %.2f, run %d/%d, %.1f s] ACC=%.4f, ' ...
                     'NMI=%.4f, ARI=%.4f, RMSE=%.4f\n'], ...
                    current_per, run_id, NUM_RUNS, toc(timer), ...
                    R.final.acc, R.final.nmi, R.final.ari, ...
                    R.evaluation.completion_rmse_mean);
            save(checkpoint_file, 'results_table', 'all_runs_details', ...
                 'config_base', 'FORMAL_MODE', '-v7.3');
        end

        new_row = table(current_per, mean(acc_runs), std(acc_runs), ...
            mean(nmi_runs), std(nmi_runs), mean(ari_runs), std(ari_runs), ...
            mean(purity_runs), std(purity_runs), ...
            mean(rmse_runs, 'omitnan'), std(rmse_runs, 'omitnan'), ...
            mean(nrmse_runs, 'omitnan'), std(nrmse_runs, 'omitnan'), ...
            'VariableNames', {'PER', 'ACC_Mean', 'ACC_Std', ...
            'NMI_Mean', 'NMI_Std', 'ARI_Mean', 'ARI_Std', ...
            'Purity_Mean', 'Purity_Std', 'RMSE_Mean', 'RMSE_Std', ...
            'NRMSE_Mean', 'NRMSE_Std'});
        results_table = [results_table; new_row]; %#ok<AGROW>
    end

    fprintf('\n======================================================\n');
    fprintf('  FINAL RESULTS\n');
    fprintf('======================================================\n');
    disp(results_table);

    result_stem = sprintf('results_Handwritten_%s_%s', profile, timestamp);
    mat_file = fullfile(results_dir, [result_stem, '.mat']);
    csv_file = fullfile(results_dir, [result_stem, '.csv']);
    save(mat_file, 'results_table', 'all_runs_details', ...
         'config_base', 'FORMAL_MODE', '-v7.3');
    writetable(results_table, csv_file);
    fprintf('Saved MAT: %s\n', mat_file);
    fprintf('Saved CSV: %s\n', csv_file);
end
